/* Dataset audit: coverage, duplicates, identity collisions, ratings, buckets. Writes docs/data-quality.md */
import { writeFileSync, mkdirSync } from 'node:fs';
import { TEAMS, ALL_PLAYERS, VERSIONS, BUCKETS, ONE_CLUB_KEYS, isChampionTeam, NATION_TEAMS, surnameOf, PLAYER_OF_THE_YEAR } from '../src/data/index';
import { validateDataset } from '../src/data/validate';
import { CAPTAINS } from '../src/data/captains';

const errors: string[] = [];
const warnings: string[] = [];

// structural validation (shared with the tests and any importer)
const report = validateDataset(TEAMS, { captains: CAPTAINS, potyYears: PLAYER_OF_THE_YEAR });
for (const e of report.errors) errors.push(`[${e.code}] ${e.where}: ${e.msg}`);
for (const w of report.warnings) warnings.push(`[${w.code}] ${w.where}: ${w.msg}`);

// same name, different person ids (possible identity split) and same person id, different names
const byName = new Map<string, Set<string>>();
for (const p of ALL_PLAYERS) {
  if (!byName.has(p.name)) byName.set(p.name, new Set());
  byName.get(p.name)!.add(p.person);
}
for (const [n, ids] of byName) if (ids.size > 1) warnings.push(`Homonym kept apart on purpose: ${n} → ${[...ids].join(', ')}`);
for (const [id, vs] of VERSIONS) {
  const nats = new Set(vs.map((v) => v.nat));
  if (nats.size > 1) warnings.push(`Dual international (per-team nationality kept): ${id}: ${[...nats].join(' / ')}`);
  const prim = new Set(vs.map((v) => v.pos[0]));
  if (prim.size > 1) warnings.push(`Position change across eras for ${vs[0].name}: ${vs.map((v) => `${v.teamEra}=${v.pos.join('/')}`).join(', ')}`);
}
// near-duplicate surnames with similar first names (spelling drift)
const surnames = new Map<string, string[]>();
for (const [, vs] of VERSIONS) {
  const s = surnameOf(vs[0].name).toLowerCase();
  if (!surnames.has(s)) surnames.set(s, []);
  surnames.get(s)!.push(vs[0].name);
}
for (const [, names] of surnames) {
  for (let i = 0; i < names.length; i++) for (let j = i + 1; j < names.length; j++) {
    const a = names[i].split(' ')[0].toLowerCase(), b = names[j].split(' ')[0].toLowerCase();
    if (a !== b && (a.startsWith(b.slice(0, 3)) || b.startsWith(a.slice(0, 3)))) warnings.push(`Check spelling drift: ${names[i]} vs ${names[j]}`);
  }
}

const ratings = ALL_PLAYERS.map((p) => p.rating).sort((a, b) => a - b);
const pct = (q: number) => ratings[Math.floor(q * (ratings.length - 1))];
const buckets = Object.fromEntries(BUCKETS.map((b) => [b, TEAMS.filter((t) => t.bucket === b).length]));
const conf = { high: 0, medium: 0, low: 0 } as Record<string, number>;
for (const p of ALL_PLAYERS) conf[p.conf]++;
const multi = [...VERSIONS.values()].filter((v) => v.length > 1).length;

const lines = [
  '# ERA XV — data quality report',
  '',
  `Generated by \`npm run audit:data\`.`,
  '',
  '## Volume',
  `- Team-eras: **${TEAMS.length}** (${NATION_TEAMS.length} national sides incl. Lions, ${TEAMS.length - NATION_TEAMS.length} clubs)`,
  `- Player versions: **${ALL_PLAYERS.length}**, distinct players: **${VERSIONS.size}**, with 2+ versions: **${multi}**`,
  `- Era buckets: ${Object.entries(buckets).map(([k, v]) => `${k} ${v}`).join(' · ')}`,
  `- Champions pool (RWC / European Cup / Super Rugby winners): ${TEAMS.filter(isChampionTeam).length}`,
  `- One Club eligible: ${ONE_CLUB_KEYS.join(', ')}`,
  `- Historic captains recorded: ${Object.keys(CAPTAINS).length} team-eras (others: captain chosen on rating, labelled as such)`,
  `- Goal-kickers (goal-kicking ≥ 80): ${ALL_PLAYERS.filter((p) => p.kicker).length} versions`,
  `- Ratings: min ${ratings[0]}, p10 ${pct(0.1)}, median ${pct(0.5)}, p90 ${pct(0.9)}, max ${ratings[ratings.length - 1]}; 95+: ${ratings.filter((r) => r >= 95).length}`,
  `- Confidence: high ${conf.high}, medium ${conf.medium}, low ${conf.low}`,
  '',
  `## Errors (${errors.length})`,
  ...errors.map((e) => `- ${e}`),
  '',
  `## Editorial review (${warnings.length})`,
  ...warnings.map((w) => `- ${w}`),
  '',
];
mkdirSync('docs', { recursive: true });
writeFileSync('docs/data-quality.md', lines.join('\n'));
console.log(lines.slice(0, 16).join('\n'));
console.log(`errors: ${errors.length}, warnings: ${warnings.length}`);
if (errors.length) { console.log(errors.join('\n')); process.exit(1); }
