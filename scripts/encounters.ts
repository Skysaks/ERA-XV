/**
 * Encounter rarity, measured: how often each player version is offered in a full-pool draft.
 * Runs N classic drafts on fixed seeds with the real director and counts, per version, the drafts in which it was offered.
 * Nothing here changes a draw: the label describes the engine, it does not steer it (docs/LAUNCH.md, "Rareté").
 *
 *   npx tsx scripts/encounters.ts            # N=6000, writes src/data/encounters.ts
 *   N=2000 npx tsx scripts/encounters.ts --dry
 */
import { writeFileSync } from 'node:fs';
import { ALL_PLAYERS } from '../src/data/index';
import { DATA_VERSION, ENGINE_VERSION, newDraft, pickOption } from '../src/engine/index';
import { hashStr } from '../src/engine/rng';

const N = Number(process.env.N ?? 6000);
/** share of versions labelled, from the rarest up */
const VERY_RARE = 0.01;
const RARE = 0.05;

const met = new Map<string, number>();
const t0 = Date.now();
for (let i = 0; i < N; i++) {
  let s = newDraft({ seed: hashStr(`encounters:${i}`) >>> 0, mode: 'classic', plan: 'balanced', ruleset: 'intl', engine: ENGINE_VERSION });
  const seen = new Set<string>();
  while (s.offer) {
    for (const k of s.offer.options) seen.add(k);
    s = pickOption(s, (i + s.round) % s.offer.options.length);
  }
  for (const k of seen) met.set(k, (met.get(k) ?? 0) + 1);
}
const rows = ALL_PLAYERS.map((p) => ({ key: p.key, rating: p.rating, rate: (met.get(p.key) ?? 0) / N })).sort((a, b) => a.rate - b.rate || a.key.localeCompare(b.key));
const nVery = Math.max(1, Math.round(rows.length * VERY_RARE));
const nRare = Math.max(nVery, Math.round(rows.length * RARE));
const labelled = rows.slice(0, nRare);
const meanRating = (xs: typeof rows) => xs.reduce((a, x) => a + x.rating, 0) / xs.length;

// per version: [tier (2 very rare, 1 rare), drafts per 10,000 in which it is offered]
const entries = labelled.map((x, i) => `  ${JSON.stringify(x.key)}: [${i < nVery ? 2 : 1}, ${Math.round(x.rate * 10000)}],`).join('\n');
const out = `/* Generated by scripts/encounters.ts on ${N} classic drafts — do not edit by hand. Regenerate after any data or draw change. */
/** Measured encounter rarity. It labels how rarely a version is offered; it never weights a draw or a rating. */
export const ENCOUNTERS_META = { dataVersion: ${DATA_VERSION}, engine: ${ENGINE_VERSION}, drafts: ${N}, veryRareShare: ${VERY_RARE}, rareShare: ${RARE} } as const;
/** version key → [tier: 2 very rare · 1 rare, drafts per 10,000 offering it] */
export const ENCOUNTERS: Record<string, [1 | 2, number]> = {
${entries}
};
`;
console.log(`${N} drafts in ${((Date.now() - t0) / 1000).toFixed(1)} s · versions ${rows.length} · labelled ${nRare} (very rare ${nVery})`);
console.log(`offer rate: rarest ${(rows[0].rate * 100).toFixed(2)} % · rare threshold ${(labelled[labelled.length - 1].rate * 100).toFixed(2)} % · median ${(rows[Math.floor(rows.length / 2)].rate * 100).toFixed(2)} % · most offered ${(rows[rows.length - 1].rate * 100).toFixed(2)} %`);
console.log(`mean rating: labelled ${meanRating(labelled).toFixed(1)} vs all ${meanRating(rows).toFixed(1)} (rarity ≠ strength)`);
if (!process.argv.includes('--dry')) writeFileSync(new URL('../src/data/encounters.ts', import.meta.url), out);
